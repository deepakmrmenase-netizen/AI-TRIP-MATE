def _render_india_explorer(o_name: str, o_coords):
    """All-India map from cheap trips to royal / luxury stays, with filters and 'route to this place'."""
    df = load_india_places()
    st.markdown('<div class="tm-section-header">🇮🇳 Explore India - from budget trips to royal palaces</div>', unsafe_allow_html=True)
    if df.empty:
        st.info("India place data is not available - please upload the latest data_loader.py.")
        return
    st.caption("Per-person estimates for a 2-3 day trip (stay, food, local travel, entry). Verify before booking.")

    def _reset_filters():
        for k in ("ie_tier", "ie_cat", "ie_state"):
            st.session_state[k] = "All"

    # Smart filters: each box only offers choices that really have places, with counts.
    ALL = "All"
    for k in ("ie_tier", "ie_cat", "ie_state"):
        st.session_state.setdefault(k, ALL)

    def _val(key):
        v = st.session_state.get(key, ALL)
        return v.split("  (")[0] if v else ALL

    def _subset(skip):
        d = df
        if skip != "tier" and _val("ie_tier") != ALL:
            d = d[d["tier"] == _val("ie_tier")]
        if skip != "cat" and _val("ie_cat") != ALL:
            d = d[d["category"] == _val("ie_cat")]
        if skip != "state" and _val("ie_state") != ALL:
            d = d[d["state"] == _val("ie_state")]
        return d

    def _options(col, skip, order=None):
        d = _subset(skip)
        counts = d[col].value_counts()
        names = [n for n in (order or sorted(counts.index)) if n in counts.index]
        return [ALL] + [f"{n}  ({int(counts[n])})" for n in names]

    def _fix(key, options):
        # if the saved choice is no longer possible, go back to "All"
        names = [o.split("  (")[0] for o in options]
        cur = _val(key)
        st.session_state[key] = options[names.index(cur)] if cur in names else ALL

    o_tier, o_cat, o_state = _options("tier", "tier", TIERS), _options("category", "cat"), _options("state", "state")
    _fix("ie_tier", o_tier); _fix("ie_cat", o_cat); _fix("ie_state", o_state)

    c1, c2, c3, c4 = st.columns([3, 3, 3, 1.4])
    with c1:
        st.selectbox("💰 Budget level", o_tier, key="ie_tier",
                     help="Cheap: under ₹2,500 · Mid-range: ₹2,500-7,999 · Royal / Luxury: ₹8,000+ (per person, 2-3 days)")
    with c2:
        st.selectbox("🏷️ Type", o_cat, key="ie_cat")
    with c3:
        st.selectbox("📍 State", o_state, key="ie_state")
    with c4:
        st.write("")
        st.write("")
        st.button("🔄 Reset", key="ie_reset", use_container_width=True, on_click=_reset_filters)

    f = _subset(None)
    f = f.sort_values(["budget_min", "place"]).reset_index(drop=True)

    legend = " &nbsp;&nbsp; ".join(
        f'<span style="color:{TIER_HEX[t]};font-weight:700;">● {t}</span>' for t in TIERS)
    st.markdown(f'<div style="font-size:0.85rem;margin:4px 0 8px 0;color:#475569;"><b>{len(f)}</b> places &nbsp;|&nbsp; {legend}</div>',
                unsafe_allow_html=True)

    if f.empty:
        st.info("No places match this combination. Press 🔄 Reset, or set one box back to 'All'.")
        return

    fmap, ok = build_india_map(f)
    if ok and fmap:
        render_map(fmap, height=560)

    st.markdown("#### 🧭 Get the route to any place on this map")
    pick = st.selectbox(
        "Choose a place", options=f.index.tolist(),
        format_func=lambda i: f"{f.loc[i, 'place']} - {f.loc[i, 'state']}  ({f.loc[i, 'tier']}, from ₹{int(f.loc[i, 'budget_min']):,})",
        key="ie_pick")
    if st.button("🚗 Show route from my starting location", use_container_width=True, key="ie_go"):
        if not o_coords:
            st.error("Enter a valid starting location at the top first.")
        else:
            st.session_state["map_pending_dest"] = str(f.loc[pick, "place"])
            st.rerun()

    show = f[["place", "state", "category", "tier", "budget_min", "budget_max", "highlight"]].copy()
    show["Cost (₹, per person)"] = show.apply(lambda r: f"{int(r['budget_min']):,} - {int(r['budget_max']):,}", axis=1)
    show = show.rename(columns={"place": "Place", "state": "State", "category": "Type", "tier": "Level", "highlight": "Known for"})
    st.dataframe(show[["Place", "State", "Type", "Level", "Cost (₹, per person)", "Known for"]],
                 hide_index=True, use_container_width=True)


