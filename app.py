def page_budget_planner():
    st.markdown('<div class="tm-section-header">💰 Budget Planner</div>', unsafe_allow_html=True)
    st.markdown('<p style="color:#64748b;margin-top:-8px;">Manually calculate your trip cost and visualise the breakdown.</p>', unsafe_allow_html=True)

    col_form, col_results = st.columns([1, 1])

    with col_form:
        st.markdown("#### Enter Your Expenses (₹)")
        b_transport = st.number_input("🚌 Transportation", min_value=0, value=900, step=50)
        b_accommodation = st.number_input("🏨 Accommodation", min_value=0, value=800, step=50)
        b_food = st.number_input("🍴 Food", min_value=0, value=600, step=50)
        b_activities = st.number_input("🎯 Activities", min_value=0, value=400, step=50)
        b_shopping = st.number_input("🛍️ Shopping", min_value=0, value=200, step=50)
        b_misc = st.number_input("🔧 Miscellaneous", min_value=0, value=150, step=50)
        total_budget_input = st.number_input("💰 Your Total Budget", min_value=100, value=3500, step=100)
        travelers_input = st.number_input("👥 Number of Travelers", min_value=1, value=2, step=1)
        duration_input = st.number_input("📅 Trip Duration (days)", min_value=1, value=2, step=1)

        calculate_btn = st.button("📊 Calculate Budget", use_container_width=True, type="primary")

    with col_results:
        if calculate_btn:
            is_valid, errors = validate_budget_inputs(b_transport, b_accommodation, b_food, b_activities, b_misc)
            if not is_valid:
                for e in errors:
                    st.error(e)
            else:
                breakdown = {
                    "Transportation": b_transport,
                    "Accommodation": b_accommodation,
                    "Food": b_food,
                    "Activities": b_activities,
                    "Shopping": b_shopping,
                    "Miscellaneous": b_misc,
                }
                total_cost = sum(breakdown.values())
                metrics = calculate_budget(total_budget_input, {"_dummy": total_cost}, travelers_input, duration_input)

                # Metrics
                m1, m2 = st.columns(2)
                m1.metric("💰 Total Budget", format_inr(total_budget_input))
                m2.metric("📊 Total Cost (Est.)", format_inr(total_cost),
                          delta=f"{format_inr(metrics['remaining'])} remaining" if metrics['remaining'] >= 0 else f"Over by {format_inr(-metrics['remaining'])}")

                m3, m4 = st.columns(2)
                m3.metric("👤 Per Person", format_inr(metrics["per_person"]))
                m4.metric("📅 Per Day", format_inr(metrics["per_day"]))

                # Progress bar
                pct = min(1.0, total_cost / max(total_budget_input, 1))
                pct_color = "#16a34a" if pct < 0.85 else ("#f59e0b" if pct < 1.0 else "#ef4444")
                st.markdown(f"""
<div style="background:#f8fafc; border:1px solid #e5e7eb; border-radius:14px; padding:16px 20px; margin:12px 0;">
  <div style="font-weight:600; color:#374151; margin-bottom:8px;">Budget Usage: {pct*100:.1f}%</div>
  <div style="background:#e5e7eb; border-radius:99px; height:12px; overflow:hidden;">
    <div style="background:{pct_color}; width:{pct*100:.1f}%; height:100%; border-radius:99px;"></div>
  </div>
</div>
""", unsafe_allow_html=True)

                # Donut chart
                fig = make_donut_chart(breakdown, "Cost Breakdown")
                st.plotly_chart(fig, use_container_width=True)

                if total_cost > total_budget_input:
                    over = total_cost - total_budget_input
                    st.warning(f"⚠️ You are ₹{over:,} over your budget. Consider reducing accommodation or activities.")
                else:
                    st.success(f"✅ You are within budget! {format_inr(metrics['remaining'])} remaining.")
        else:
            st.markdown("""
<div class="tm-card" style="text-align:center; padding:40px 20px;">
  <div style="font-size:3rem; margin-bottom:12px;">📊</div>
  <div style="color:#64748b;">Enter your expenses on the left and click <strong>Calculate Budget</strong> to see the analysis.</div>
</div>
""", unsafe_allow_html=True)


