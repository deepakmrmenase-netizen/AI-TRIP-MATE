def _render_download_tab(trip: dict):
    st.markdown('<div class="tm-section-header">📥 Download Your Itinerary</div>', unsafe_allow_html=True)
    summary = trip.get("trip_summary", {})

    trip_text = generate_trip_text(trip)
    filename = f"TripMate_AI_{summary.get('destination','Trip').replace(' ','_')}_Itinerary.txt"

    st.download_button(
        label="📥 Download Itinerary (.txt)",
        data=trip_text,
        file_name=filename,
        mime="text/plain",
        use_container_width=True,
        type="primary",
    )

    col_save, _ = st.columns([1, 3])
    with col_save:
        if st.button("❤️ Save This Trip", use_container_width=True):
            saved = st.session_state.saved_trips
            trip_id = len(saved) + 1
            saved_entry = {
                "id": trip_id,
                "title": f"{summary.get('destination','Trip')} Trip #{trip_id}",
                "trip": trip,
                "text": trip_text,
            }
            st.session_state.saved_trips.append(saved_entry)
            st.success("❤️ Trip saved successfully!")

    with st.expander("👀 Preview Itinerary Text"):
        st.code(trip_text, language=None)


