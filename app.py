def page_checklist():
    st.markdown('<div class="tm-section-header">📋 Travel Checklist</div>', unsafe_allow_html=True)

    checklist = st.session_state.checklist_items
    custom = st.session_state.checklist_custom

    all_items = checklist + custom
    total = len(all_items)
    completed = 0

    # Default items
    st.markdown("#### 🎒 Essential Items")
    updated_checklist = []
    for label, checked in checklist:
        new_checked = st.checkbox(label, value=checked, key=f"check_{label}")
        updated_checklist.append((label, new_checked))
        if new_checked:
            completed += 1
    st.session_state.checklist_items = updated_checklist

    # Custom items
    if custom:
        st.markdown("#### ➕ Your Items")
        updated_custom = []
        for idx, (label, checked) in enumerate(custom):
            col_check, col_del = st.columns([5, 1])
            with col_check:
                new_checked = st.checkbox(label, value=checked, key=f"custom_{idx}")
                updated_custom.append((label, new_checked))
                if new_checked:
                    completed += 1
            with col_del:
                if st.button("🗑️", key=f"del_custom_{idx}"):
                    updated_custom.pop(-1)
                    st.rerun()
        st.session_state.checklist_custom = updated_custom

    # Add custom item
    st.markdown("---")
    col_input, col_add = st.columns([4, 1])
    with col_input:
        new_item = st.text_input("Add your own item:", placeholder="e.g. Sunscreen, hat, travel pillow")
    with col_add:
        st.markdown("<br>", unsafe_allow_html=True)
        if st.button("➕ Add", use_container_width=True):
            if new_item.strip():
                st.session_state.checklist_custom.append((new_item.strip(), False))
                st.rerun()

    # Progress
    st.markdown("---")
    pct = completed / max(total, 1)
    status_msg = "🎉 All packed! Ready to go!" if completed == total else f"📦 {completed} / {total} items packed"
    st.markdown(f'<div style="font-weight:600; color:#374151; margin-bottom:8px;">{status_msg}</div>', unsafe_allow_html=True)
    st.progress(pct)

    if completed < total:
        st.info(f"⚠️ {total - completed} item{'s' if total - completed > 1 else ''} remaining. Don't forget them!")
    else:
        st.success("✅ You're all packed! Have a safe and amazing trip! ✈️")

    # Reset
    col_r1, col_r2, col_r3 = st.columns([1, 1, 2])
    with col_r1:
        if st.button("✅ Check All", use_container_width=True):
            st.session_state.checklist_items = [(l, True) for l, _ in st.session_state.checklist_items]
            st.session_state.checklist_custom = [(l, True) for l, _ in st.session_state.checklist_custom]
            st.rerun()
    with col_r2:
        if st.button("☐ Uncheck All", use_container_width=True):
            st.session_state.checklist_items = [(l, False) for l, _ in st.session_state.checklist_items]
            st.session_state.checklist_custom = [(l, False) for l, _ in st.session_state.checklist_custom]
            st.rerun()


